/** Exact names, and the numbered ones as patterns. */
const exact = new Map();
const numbered = [];
STANDARD.forEach(([name, pretty]) => {
  if (!/\((n|m)\)/.test(name)) {
    exact.set(name, pretty);
    return;
  }
  const order = [...name.matchAll(/\((n|m)\)/g)].map((m) => m[1]);
  // Names are letters, digits and underscores apart from the placeholders.
  const source = name.replace(/\((n|m)\)/g, '(\\d+)');
  numbered.push({ pattern: new RegExp(`^${source}$`), order, pretty });
});

/**
 * The spec's pretty name for an attribute.
 *
 * @param {String} attribute e.g. `Gobo2WheelSpin`
 * @returns {String|null} null for an attribute the spec does not list
 */
export function standardPretty(attribute) {
  if (exact.has(attribute)) return exact.get(attribute);
  for (let i = 0; i < numbered.length; i += 1) {
    const { pattern, order, pretty } = numbered[i];
    const m = pattern.exec(attribute);
    if (m) {
      const value = {};
      order.forEach((letter, k) => { value[letter] = m[k + 1]; });
      return pretty.replace(/\((n|m)\)/g, (_, letter) => value[letter]);
    }
  }
  return null;
}

/**
 * Whether a file's pretty name for an attribute is its own: present and not
 * the spec's. Compared without case or surrounding space, which files vary.
 *
 * @param {String} attribute
 * @param {String} pretty as the file writes it
 * @returns {Boolean}
 */
export function isOwnPretty(attribute, pretty) {
  const own = String(pretty || '').trim();
  if (!own) return false;
  const standard = standardPretty(attribute);
  return standard === null || own.toLowerCase() !== standard.trim().toLowerCase();
}
